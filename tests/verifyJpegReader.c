static MemorySize buildAlfaVariant(const Unsigned8 *alfaPayload, MemorySize alfaPayloadSize)
{
    MemorySize segmentLength = alfaPayloadSize + 6UL;
    MemorySize cursor;
    MemorySize index;

    alfaVariant[0] = 0xFFU;
    alfaVariant[1] = 0xD8U;
    alfaVariant[2] = 0xFFU;
    alfaVariant[3] = 0xE0U;
    alfaVariant[4] = (Unsigned8)((segmentLength >> 8) & 0xFFU);
    alfaVariant[5] = (Unsigned8)(segmentLength & 0xFFU);
    alfaVariant[6] = 'A';
    alfaVariant[7] = 'L';
    alfaVariant[8] = 'F';
    alfaVariant[9] = 'A';
    cursor = 10UL;
    for (index = 0UL; index < alfaPayloadSize; index++)
    {
        alfaVariant[cursor] = alfaPayload[index];
        cursor++;
    }
    for (index = 2UL; index < sizeof(solidJpegFixture); index++)
    {
        alfaVariant[cursor] = solidJpegFixture[index];
        cursor++;
    }
    return cursor;
}

static Boolean channelNear(Unsigned8 actual, Unsigned8 expected)
{
    Integer32 difference = (Integer32)actual - (Integer32)expected;

    return (difference >= -3 && difference <= 3) ? BOOLEAN_TRUE : BOOLEAN_FALSE;
}

static Boolean everyPixelIsColour(Unsigned8 red, Unsigned8 green, Unsigned8 blue)
{
    Unsigned32 pixelIndex;

    for (pixelIndex = 0U; pixelIndex < FIXTURE_WIDTH * FIXTURE_HEIGHT; pixelIndex++)
    {
        const Unsigned8 *pixel = rgba + (MemorySize)pixelIndex * 4UL;

        if (!channelNear(pixel[0], red) || !channelNear(pixel[1], green) ||
            !channelNear(pixel[2], blue))
        {
            return BOOLEAN_FALSE;
        }
    }
    return BOOLEAN_TRUE;
}

int main(void)
{
    Unsigned32 width = 0U;
    Unsigned32 height = 0U;
    JpegReadResult result;

    printf("-- peeking at the fixture --\n");
    {
        result = jpegPeekDimensions(solidJpegFixture, sizeof(solidJpegFixture), &width, &height);
        checkThat(&failureCount, "peek reads OK", result == JPEG_READ_OK);
        checkThat(&failureCount, "peek reports 8x8", width == FIXTURE_WIDTH && height == FIXTURE_HEIGHT);
    }

    printf("\n-- decoding the fixture --\n");
    {
        Unsigned32 decodedWidth = 0U;
        Unsigned32 decodedHeight = 0U;
        Unsigned32 pixelIndex;
        Boolean allOpaque = BOOLEAN_TRUE;

        result = jpegReadToRgba(solidJpegFixture, sizeof(solidJpegFixture), rgba, RGBA_CAPACITY,
                                &decodedWidth, &decodedHeight);
        checkThat(&failureCount, "decode reads OK", result == JPEG_READ_OK);
        checkThat(&failureCount, "decode dimensions agree with the peek",
                  decodedWidth == FIXTURE_WIDTH && decodedHeight == FIXTURE_HEIGHT);
        checkThat(&failureCount, "solid colour survives the lossy round trip",
                  everyPixelIsColour(200U, 100U, 50U));
        for (pixelIndex = 0U; pixelIndex < FIXTURE_WIDTH * FIXTURE_HEIGHT; pixelIndex++)
        {
            if (rgba[(MemorySize)pixelIndex * 4UL + 3UL] != 255U)
            {
                allOpaque = BOOLEAN_FALSE;
            }
        }
        checkThat(&failureCount, "a JPEG with no ALFA segment decodes fully opaque", allOpaque);
    }

    printf("\n-- refusing what is not JPEG --\n");
    {
        static const char notJpeg[] = "this is not a JPEG, only a sentence";

        checkThat(&failureCount, "peek rejects non-JPEG input",
                  jpegPeekDimensions((const Unsigned8 *)notJpeg, sizeof(notJpeg) - 1UL,
                                     &width, &height) == JPEG_READ_INVALID);
        checkThat(&failureCount, "decode rejects non-JPEG input",
                  jpegReadToRgba((const Unsigned8 *)notJpeg, sizeof(notJpeg) - 1UL,
                                 rgba, RGBA_CAPACITY, &width, &height) == JPEG_READ_INVALID);
        checkThat(&failureCount, "peek rejects a truncated SOI",
                  jpegPeekDimensions(solidJpegFixture, 3UL, &width, &height) == JPEG_READ_INVALID);
    }

    printf("\n-- the ALFA segment --\n");
    {
        static const Unsigned8 alfaPayload[] = { 0x01U, 0x00U, 0x80U, 0xC3U, 0xFFU };
        MemorySize variantSize = buildAlfaVariant(alfaPayload, sizeof(alfaPayload));

        result = jpegReadToRgba(alfaVariant, variantSize, rgba, RGBA_CAPACITY, &width, &height);
        checkThat(&failureCount, "a JPEG carrying an ALFA segment still decodes", result == JPEG_READ_OK);
        checkThat(&failureCount, "colour decodes with the ALFA segment present",
                  everyPixelIsColour(200U, 100U, 50U));
        checkThat(&failureCount, "the literal run lands per pixel",
                  rgba[3] == 0x00U && rgba[7] == 0x80U);
        checkThat(&failureCount, "the repeat run lands per pixel",
                  rgba[2UL * 4UL + 3UL] == 0xFFU && rgba[63UL * 4UL + 3UL] == 0xFFU);
    }

    printf("\n-- a truncated ALFA segment --\n");
    {
        static const Unsigned8 shortAlfaPayload[] = { 0x01U, 0x00U, 0x80U };
        MemorySize variantSize = buildAlfaVariant(shortAlfaPayload, sizeof(shortAlfaPayload));

        result = jpegReadToRgba(alfaVariant, variantSize, rgba, RGBA_CAPACITY, &width, &height);
        checkThat(&failureCount, "a truncated ALFA segment still decodes", result == JPEG_READ_OK);
        checkThat(&failureCount, "the pixels the payload covered keep their alpha",
                  rgba[3] == 0x00U && rgba[7] == 0x80U);
        checkThat(&failureCount, "the pixels it did not fall back to opaque",
                  rgba[2UL * 4UL + 3UL] == 0xFFU && rgba[63UL * 4UL + 3UL] == 0xFFU);
    }

    return checkSummarize(failureCount, "JPEG reader");
}
