Boolean builtinFontHasInk(Unsigned32 codePoint, Unsigned32 column, Unsigned32 row)
{
    Unsigned32 index;

    if (codePoint < BUILTIN_FONT_FIRST_CHARACTER ||
        codePoint >= BUILTIN_FONT_FIRST_CHARACTER + BUILTIN_FONT_CHARACTER_COUNT)
    {
        return BOOLEAN_FALSE;
    }
    if (column >= BUILTIN_FONT_WIDTH || row >= BUILTIN_FONT_HEIGHT)
    {
        return BOOLEAN_FALSE;
    }
    index = codePoint - BUILTIN_FONT_FIRST_CHARACTER;
    return (glyphCells[index][(row * BUILTIN_FONT_WIDTH) + column] == '#') ? BOOLEAN_TRUE
                                                                          : BOOLEAN_FALSE;
}
